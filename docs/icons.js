const SLOT_MOTIF = { weapon: "blade", armour: "plate", trinket: "gem" };
const hash = (s) => { let h = 0; for (let i = 0; i < s.length; i++) h = (h * 31 + s.charCodeAt(i)) | 0; return Math.abs(h); };

function resolve(item) {
  const id = typeof item === "string" ? item : (item && item.id) || "";
  const row = ITEM_ART[id];
  if (row) { const [motif, tint, variant] = row.split(" "); return { motif, tint, variant }; }
  const slot = (item && item.slot) || "trinket";
  return { motif: SLOT_MOTIF[slot] || "gem", tint: TINT_ORDER[hash(id) % TINT_ORDER.length], variant: "" };
}
function art(motif, tint, size, variant) {
  const fn = M[motif] || M.gem, q = T[tint] || T.gold;
  size = size || 64;
  return `<svg ${NS} viewBox="0 0 64 64" width="${size}" height="${size}" focusable="false" aria-hidden="true">${fn(q, variant || "")}</svg>`;
}
function item(it, size) {
  const r = resolve(it);
  return art(r.motif, r.tint, size, r.variant);
}

